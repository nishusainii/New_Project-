    @staticmethod
    def generate_keypair() -> WireGuardKeypair:
        """Generates standard Curve25519 WireGuard keypair using Python cryptography."""
        priv = x25519.X25519PrivateKey.generate()
        priv_bytes = priv.private_bytes(
            encoding=serialization.Encoding.Raw,
            format=serialization.PrivateFormat.Raw,
            encryption_algorithm=serialization.NoEncryption()
        )
        pub = priv.public_key()
        pub_bytes = pub.public_bytes(
            encoding=serialization.Encoding.Raw,
            format=serialization.PublicFormat.Raw
        )
        return WireGuardKeypair(
            private_key=base64.b64encode(priv_bytes).decode("ascii"),
            public_key=base64.b64encode(pub_bytes).decode("ascii")
        )

    @staticmethod
    def public_key_from_private(private_key_b64: str) -> str:
        """Derives Curve25519 WireGuard public key from a base64 private key."""
        priv_bytes = base64.b64decode(private_key_b64.strip())
        priv = x25519.X25519PrivateKey.from_private_bytes(priv_bytes)
        pub = priv.public_key()
        pub_bytes = pub.public_bytes(
            encoding=serialization.Encoding.Raw,
            format=serialization.PublicFormat.Raw
        )
        return base64.b64encode(pub_bytes).decode("ascii")

    @staticmethod
    def generate_psk() -> str:
        """Generates a 32-byte pre-shared key (PSK) base64-encoded."""
        return base64.b64encode(secrets.token_bytes(32)).decode("ascii")

    @staticmethod
    def validate_key(key: str) -> bool:
        """Checks if key is valid 32-byte Base64-encoded string."""
        try:
            cleaned = (key or "").strip()
            decoded = base64.b64decode(cleaned, validate=True)
            return len(cleaned) == 44 and len(decoded) == 32
        except Exception:
            return False

    @staticmethod
    def render_server_config(
        server_address: str,
        server_port: int,
        server_private_key: str,
        peers: List[dict],
        extra_directives: str = ""
    ) -> str:
        # Guard against invalid Fernet tokens being written as WireGuard keys
        valid_priv = server_private_key if is_wireguard_key(server_private_key) else ""
        if not valid_priv and os.path.exists(WG_CONFIG_PATH):
            try:
                with open(WG_CONFIG_PATH, "r", encoding="utf-8") as f:
                    for line in f:
                        if line.strip().lower().startswith("privatekey"):
                            cand = line.split("=", 1)[1].strip()
                            if is_wireguard_key(cand):
                                valid_priv = cand
                                break
            except Exception:
                pass

        lines = [
            "# WireGate Server Configuration",
            "# Auto-generated by WireGate Control Center",
            "",
            "[Interface]",
            f"Address = {server_address}",
            f"ListenPort = {server_port}",
            f"PrivateKey = {valid_priv}",
        ]

        if extra_directives and extra_directives.strip():
            lines.extend([line.strip() for line in extra_directives.strip().splitlines() if line.strip()])

        for peer in peers:
            if not peer.get("enabled", True):
                continue
            lines.extend([
                "",
                f"# Peer: {peer.get('name', 'Unknown')}",
                "[Peer]",
                f"PublicKey = {peer['public_key']}",
            ])
            # Only append PSK if it is a valid 32-byte WireGuard key
            if peer.get("psk") and is_wireguard_key(peer["psk"]):
                lines.append(f"PresharedKey = {peer['psk']}")
            lines.append(f"AllowedIPs = {peer['allowed_ips']}")
            if peer.get("endpoint"):
                lines.append(f"Endpoint = {peer['endpoint']}")
            if peer.get("keepalive"):
                lines.append(f"PersistentKeepalive = {peer['keepalive']}")

        return "\n".join(lines) + "\n"

    @staticmethod
    def render_client_config(
        client_private_key: str,
        client_address: str,
        server_public_key: str,
        server_endpoint: str,
        server_port: int = 443,
        dns: Optional[str] = None,
        psk: Optional[str] = None,
        mtu: int = 1420,
        keepalive: int = 25,
        allowed_ips_route: str = "0.0.0.0/0, ::/0"
    ) -> str:
        """Renders client .conf configuration file."""
        if ":" in server_endpoint:
            endpoint_str = server_endpoint
        else:
            endpoint_str = f"{server_endpoint}:{server_port}"

        lines = [
            "# WireGuard Enterprise Client Configuration",
            "[Interface]",
            f"PrivateKey = {client_private_key}",
            f"Address = {client_address}",
        ]
        if dns and str(dns).strip():
            lines.append(f"DNS = {str(dns).strip()}")
        if mtu:
            lines.append(f"MTU = {mtu}")
        lines.append("")
        lines.extend([
            "[Peer]",
            f"PublicKey = {server_public_key}",
            f"Endpoint = {endpoint_str}",
            f"AllowedIPs = {allowed_ips_route}",
        ])
        if psk:
            lines.append(f"PresharedKey = {psk}")
        if keepalive:
            lines.append(f"PersistentKeepalive = {keepalive}")

        return "\n".join(lines) + "\n"

    @classmethod
    def parse_config_text(cls, content: str) -> Optional[dict]:
        """
        Parses configuration text into interface and peer records.
        Supports:
        1. JSON format (e.g. wg0.json)
        2. Standard WireGuard .conf format ([Interface], [Peer])
        3. Bare [Peer] blocks
        """
        if not content or not content.strip():
            return None

        content_clean = content.strip()

        # 1. Attempt JSON parsing
        if content_clean.startswith("{"):
            try:
                data = json.loads(content_clean)
                addr = data.get("address", ["172.29.250.1/24"])
                if isinstance(addr, list) and addr:
                    addr_str = addr[0]
                else:
                    addr_str = str(addr or "172.29.250.1/24")

                dns_val = data.get("dns", "")
                if isinstance(dns_val, list):
                    dns_str = ", ".join(dns_val)
                else:
                    dns_str = str(dns_val or "")

                iface_data = {
                    "address": addr_str,
                    "listen_port": int(data.get("listen_port") or 443),
                    "mtu": int(data.get("mtu") or 1420),
                    "private_key": data.get("private_key") or "",
                    "endpoint": data.get("endpoint") or "",
                    "dns": dns_str,
                    "extra_directives": ""
                }
                peers = []
                for p in data.get("peers", []):
                    pub = p.get("public_key")
                    if not pub:
                        continue
                    allowed = p.get("allowed_ips", [])
                    if isinstance(allowed, list):
                        allowed_str = ", ".join(allowed)
                    else:
                        allowed_str = str(allowed or p.get("client_address") or "")

                    peers.append({
                        "name": p.get("name") or f"Peer-{len(peers) + 1}",
                        "public_key": pub,
                        "allowed_ips": allowed_str,
                        "endpoint": p.get("endpoint") or "",
                        "psk": p.get("preshared_key") or p.get("psk") or "",
                        "client_private_key": p.get("client_private_key") or "",
                        "keepalive": int(p.get("persistent_keepalive") or p.get("keepalive") or 25),
                        "device_type": p.get("category") or p.get("device_type") or "laptop",
                        "tunnel_mode": "full" if p.get("full_tunnel", True) else "split",
                        "enabled": p.get("enabled", True)
                    })
                return {"interface": iface_data, "peers": peers}
            except Exception:
                pass

        # 2. Parse INI .conf format
        lines = content.splitlines()
        iface_data = {
            "address": "172.29.250.1/24",
            "listen_port": 443,
            "mtu": 1420,
            "private_key": "",
            "endpoint": "",
            "dns": "",
            "extra_directives": []
        }
        peers = []
        current_section = None
        current_peer = {}
        current_name = None

        for line in lines:
            line = line.strip()
            if not line:
                continue
            if line.startswith("#"):
                match = re.search(r"#\s*(?:Peer|Name|Client)[\s:=]+([^\n\r]+)", line, re.IGNORECASE)
                c_name = match.group(1).strip() if match else ""
                if not c_name and not line.startswith("# WireGate") and not line.startswith("# Auto-generated"):
                    raw_comment = line.lstrip("#").strip()
                    if raw_comment and not raw_comment.startswith("["):
                        c_name = raw_comment

                if c_name:
                    if current_section == "peer" and current_peer and current_peer.get("name", "").startswith("Peer-"):
                        current_peer["name"] = c_name
                    else:
                        current_name = c_name
                continue

            if line.startswith("[Interface]"):
                current_section = "interface"
                continue
            elif line.startswith("[Peer]"):
                if current_peer and current_peer.get("public_key"):
                    peers.append(current_peer)
                current_section = "peer"
                current_peer = {
                    "name": current_name or f"Peer-{len(peers) + 1}",
                    "public_key": "",
                    "allowed_ips": "",
                    "endpoint": "",
                    "psk": "",
                    "keepalive": 25,
                    "enabled": True,
                    "device_type": "laptop",
                    "tunnel_mode": "full"
                }
                current_name = None
                continue

            if "=" in line:
                key, val = [x.strip() for x in line.split("=", 1)]
                key_lower = key.lower()
                if current_section == "interface":
                    if key_lower == "address": iface_data["address"] = val
                    elif key_lower == "listenport":
                        iface_data["listen_port"] = int(val) if val.isdigit() else 443
                    elif key_lower == "mtu":
                        iface_data["mtu"] = int(val) if val.isdigit() else 1420
                    elif key_lower == "privatekey": iface_data["private_key"] = val
                    elif key_lower == "dns": iface_data["dns"] = val
                    elif key_lower == "endpoint": iface_data["endpoint"] = val
                    else:
                        iface_data["extra_directives"].append(f"{key} = {val}")
                elif current_section == "peer":
                    if key_lower == "publickey": current_peer["public_key"] = val
                    elif key_lower == "allowedips": current_peer["allowed_ips"] = val
                    elif key_lower == "endpoint": current_peer["endpoint"] = val
                    elif key_lower == "presharedkey": current_peer["psk"] = val
                    elif key_lower == "persistentkeepalive":
                        current_peer["keepalive"] = int(val) if val.isdigit() else 25

        if current_peer and current_peer.get("public_key"):
            peers.append(current_peer)

        iface_data["extra_directives"] = "\n".join(iface_data["extra_directives"])
        return {"interface": iface_data, "peers": peers}

    @classmethod
    def parse_kernel_dump(cls, interface: str = WG_INTERFACE) -> Optional[dict]:
        """
        Extracts interface settings and peer records directly from kernel memory via `wg show <interface> dump`.
        """
        wg_bin = shutil.which("wg")
        if not wg_bin:
            return None

        try:
            proc = subprocess.run([wg_bin, "show", interface, "dump"], capture_output=True, text=True, timeout=5)
            if proc.returncode != 0 or not proc.stdout.strip():
                return None

            lines = proc.stdout.strip().splitlines()
            if not lines:
                return None

            iface_parts = lines[0].split("\t")
            iface_priv = iface_parts[0].strip() if len(iface_parts) > 0 and iface_parts[0].strip() != "(none)" else ""
            iface_pub = iface_parts[1].strip() if len(iface_parts) > 1 else ""
            iface_port = int(iface_parts[2].strip()) if len(iface_parts) > 2 and iface_parts[2].strip().isdigit() else 443

            iface_data = {
                "address": "172.29.250.1/24",
                "listen_port": iface_port,
                "mtu": 1420,
                "private_key": iface_priv,
                "public_key": iface_pub,
                "endpoint": "",
                "dns": "",
                "extra_directives": ""
            }

            peers = []
            for idx, line in enumerate(lines[1:], start=1):
                parts = line.split("\t")
                if len(parts) >= 4:
                    pub = parts[0].strip()
                    psk = parts[1].strip() if parts[1].strip() != "(none)" else ""
                    endpoint = parts[2].strip() if parts[2].strip() != "(none)" else ""
                    allowed_ips = parts[3].strip() if parts[3].strip() != "(none)" else ""
                    keepalive = int(parts[7].strip()) if len(parts) > 7 and parts[7].strip().isdigit() else 25

                    peers.append({
                        "name": f"Peer-{idx}",
                        "public_key": pub,
                        "allowed_ips": allowed_ips,
                        "endpoint": endpoint,
                        "psk": psk,
                        "keepalive": keepalive,
                        "enabled": True,
                        "device_type": "laptop",
                        "tunnel_mode": "full"
                    })

            return {"interface": iface_data, "peers": peers}
        except Exception:
            return None

    @classmethod
    def extract_peer_blocks_with_keys(cls, config_text: str) -> List[Tuple[str, str]]:
        """
        Parses raw configuration text and returns a list of (public_key, full_block_text) tuples.
        Includes any preceding comments associated with that peer.
        """
        if not config_text or not config_text.strip():
            return []

        blocks: List[Tuple[str, str]] = []
        lines = config_text.splitlines()
        current_lines: List[str] = []
        current_pubkey = ""
        in_peer = False
        pending_comments: List[str] = []

        for line in lines:
            stripped = line.strip()
            if not stripped:
                if in_peer and current_lines and current_pubkey:
                    blocks.append((current_pubkey, "\n".join(current_lines).strip()))
                    current_lines = []
                    current_pubkey = ""
                    in_peer = False
                pending_comments = []
                continue

            if stripped.startswith("[Interface]"):
                if in_peer and current_lines and current_pubkey:
                    blocks.append((current_pubkey, "\n".join(current_lines).strip()))
                in_peer = False
                current_lines = []
                current_pubkey = ""
                pending_comments = []
                continue

            if stripped.startswith("#"):
                if stripped.lower().startswith(("# peer", "# name", "# client")):
                    if in_peer and current_lines and current_pubkey:
                        blocks.append((current_pubkey, "\n".join(current_lines).strip()))
                        current_lines = []
                        current_pubkey = ""
                        in_peer = False
                if in_peer:
                    current_lines.append(line)
                else:
                    pending_comments.append(line)
                continue

            if stripped.startswith("[Peer]"):
                if in_peer and current_lines and current_pubkey:
                    blocks.append((current_pubkey, "\n".join(current_lines).strip()))
                in_peer = True
                current_lines = list(pending_comments)
                pending_comments = []
                current_lines.append(line)
                current_pubkey = ""
                continue

            if in_peer:
                current_lines.append(line)
                if stripped.lower().startswith("publickey"):
                    parts = stripped.split("=", 1)
                    if len(parts) == 2:
                        current_pubkey = parts[1].strip()

        if in_peer and current_lines and current_pubkey:
            blocks.append((current_pubkey, "\n".join(current_lines).strip()))

        return blocks

    @classmethod
    def discover_all_host_data(cls, interface: str = WG_INTERFACE) -> dict:
        """
        Deep discovery scanning:
        1. /etc/wireguard/wg0.conf
        2. All /etc/wireguard/wg0.conf.bak.* files (from newest to oldest)
        3. Any other /etc/wireguard/*.conf files
        4. Live Linux kernel memory via `wg show <interface> dump`
        Returns merged interface settings and all discovered unique peers.
        """
        dir_name = os.path.dirname(WG_CONFIG_PATH) if os.path.exists(os.path.dirname(WG_CONFIG_PATH)) else "/etc/wireguard"
        base_name = os.path.basename(WG_CONFIG_PATH)

        files_to_scan: List[str] = []
        if os.path.exists(WG_CONFIG_PATH):
            files_to_scan.append(WG_CONFIG_PATH)

        # Only scan the primary active configuration file (never resurrect deleted peers from historical .bak files)
        if os.path.exists(dir_name):
            try:
                # Find other active .conf files if primary WG_CONFIG_PATH not present
                if not os.path.exists(WG_CONFIG_PATH):
                    other_confs = [
                        os.path.join(dir_name, f) for f in os.listdir(dir_name)
                        if f.endswith(".conf") and not f.startswith(".")
                    ]
                    other_confs.sort(key=lambda p: os.path.getmtime(p) if os.path.exists(p) else 0, reverse=True)
                    files_to_scan.extend(other_confs)
            except Exception as e:
                logger.warning(f"Error scanning {dir_name}: {e}")

        merged_iface = {
            "address": "172.29.250.1/24",
            "listen_port": 443,
            "mtu": 1420,
            "private_key": "",
            "public_key": "",
            "endpoint": "",
            "dns": "",
            "extra_directives": ""
        }

        peers_by_pub: Dict[str, dict] = {}

        # 1. Scan all configuration and backup files
        for fpath in files_to_scan:
            try:
                if not os.path.exists(fpath):
                    continue
                with open(fpath, "r", encoding="utf-8", errors="ignore") as f:
                    content = f.read()
                parsed = cls.parse_config_text(content)
                if not parsed:
                    continue

                f_iface = parsed.get("interface", {})
                if f_iface:
                    if f_iface.get("private_key") and is_wireguard_key(f_iface["private_key"]):
                        if not merged_iface["private_key"]:
                            merged_iface["private_key"] = f_iface["private_key"]
                            try:
                                merged_iface["public_key"] = cls.public_key_from_private(f_iface["private_key"])
                            except Exception:
                                pass
                    if f_iface.get("address") and f_iface["address"].strip():
                        if merged_iface["address"] == "172.29.250.1/24" or not merged_iface["address"]:
                            merged_iface["address"] = f_iface["address"].strip()
                    if f_iface.get("listen_port") and str(f_iface["listen_port"]).isdigit():
                        merged_iface["listen_port"] = int(f_iface["listen_port"])
                    if f_iface.get("mtu") and str(f_iface["mtu"]).isdigit():
                        merged_iface["mtu"] = int(f_iface["mtu"])
                    if f_iface.get("endpoint"):
                        merged_iface["endpoint"] = f_iface["endpoint"]
                    if f_iface.get("dns"):
                        merged_iface["dns"] = f_iface["dns"]
                    if f_iface.get("extra_directives") and f_iface["extra_directives"].strip():
                        merged_iface["extra_directives"] = f_iface["extra_directives"].strip()

                for p in parsed.get("peers", []):
                    pub = p.get("public_key", "").strip()
                    if not pub or not is_wireguard_key(pub):
                        continue
                    if pub not in peers_by_pub:
                        peers_by_pub[pub] = dict(p)
                    else:
                        cur = peers_by_pub[pub]
                        if (not cur.get("name") or cur.get("name", "").startswith("Peer-")) and p.get("name") and not p.get("name", "").startswith("Peer-"):
                            cur["name"] = p["name"]
                        if (not cur.get("allowed_ips") or cur.get("allowed_ips") in ["0.0.0.0/0", ""]) and p.get("allowed_ips") and p.get("allowed_ips") != "0.0.0.0/0":
                            cur["allowed_ips"] = p["allowed_ips"]
                        if not cur.get("endpoint") and p.get("endpoint"):
                            cur["endpoint"] = p["endpoint"]
                        if not cur.get("psk") and p.get("psk") and is_wireguard_key(p["psk"]):
                            cur["psk"] = p["psk"]
                        if not cur.get("client_private_key") and p.get("client_private_key"):
                            cur["client_private_key"] = p["client_private_key"]
            except Exception as e:
                logger.warning(f"Error parsing file {fpath}: {e}")

        # 2. Inspect Live Kernel Dump (wg show <interface> dump)
        kernel_data = cls.parse_kernel_dump(interface)
        if kernel_data:
            k_iface = kernel_data.get("interface", {})
            if k_iface:
                if not merged_iface["private_key"] and k_iface.get("private_key") and is_wireguard_key(k_iface["private_key"]):
                    merged_iface["private_key"] = k_iface["private_key"]
                    try:
                        merged_iface["public_key"] = cls.public_key_from_private(k_iface["private_key"])
                    except Exception:
                        pass
                if not merged_iface["public_key"] and k_iface.get("public_key"):
                    merged_iface["public_key"] = k_iface["public_key"]
                if k_iface.get("listen_port"):
                    merged_iface["listen_port"] = k_iface["listen_port"]

            for kp in kernel_data.get("peers", []):
                pub = kp.get("public_key", "").strip()
                if not pub or not is_wireguard_key(pub):
                    continue
                if pub not in peers_by_pub:
                    peers_by_pub[pub] = dict(kp)
                else:
                    cur = peers_by_pub[pub]
                    if not cur.get("endpoint") and kp.get("endpoint"):
                        cur["endpoint"] = kp["endpoint"]
                    if (not cur.get("allowed_ips") or cur.get("allowed_ips") in ["0.0.0.0/0", ""]) and kp.get("allowed_ips"):
                        cur["allowed_ips"] = kp["allowed_ips"]
                    if not cur.get("psk") and kp.get("psk") and is_wireguard_key(kp["psk"]):
                        cur["psk"] = kp["psk"]

        if merged_iface.get("private_key") and not merged_iface.get("public_key"):
            try:
                merged_iface["public_key"] = cls.public_key_from_private(merged_iface["private_key"])
            except Exception:
                pass

        return {
            "interface": merged_iface,
            "peers": list(peers_by_pub.values())
        }

    @classmethod
    def parse_config_file(cls, conf_path: str = WG_CONFIG_PATH) -> Optional[dict]:
        """Parses an existing WireGuard .conf or .json file into interface settings and peer records."""
        if not os.path.exists(conf_path):
            return None

        try:
            with open(conf_path, "r", encoding="utf-8") as f:
                content = f.read()
            return cls.parse_config_text(content)
        except Exception:
            return None

    @classmethod
    def apply_syncconf(cls, rendered_config: str, interface: str = WG_INTERFACE, allow_peer_removal: bool = False) -> Tuple[bool, str]:
        """
        Applies config changes using zero-downtime wg syncconf.
        Handles direct execution, agent mode, or dry-run.
        """
        mode = WG_EXECUTION_MODE.lower()

        if mode == "dry-run":
            return True, "Dry-run mode active. Configuration verified and syntax validated without applying to kernel."

        if mode == "agent":
            return cls._apply_via_agent(rendered_config)

        if mode == "direct":
            return cls._apply_direct(rendered_config, interface, allow_peer_removal=allow_peer_removal)

        return False, f"Unknown execution mode: {mode}"

    @classmethod
    def _apply_direct(cls, rendered_config: str, interface: str, allow_peer_removal: bool = False) -> Tuple[bool, str]:
        """Directly updates WireGuard interface on host/container with peer preservation."""
        wg_bin = shutil.which("wg")
        if not wg_bin:
            return False, "WireGuard tools ('wg') not found in PATH."

        ip_bin = shutil.which("ip")
        temp_conf = f"/tmp/{interface}_sync.conf"
        stripped_conf = f"/tmp/{interface}_stripped.conf"
        try:
            # SAFEGUARD 1: Check existing file and create timestamped backup before any overwrite
            existing_file_content = ""
            if os.path.exists(WG_CONFIG_PATH):
                try:
                    with open(WG_CONFIG_PATH, "r", encoding="utf-8") as f:
                        existing_file_content = f.read()

                    # Create timestamped backup
                    ts = int(time.time())
                    bak_path = f"{WG_CONFIG_PATH}.bak.{ts}"
                    shutil.copy2(WG_CONFIG_PATH, bak_path)

                    # Retain last 20 backups
                    dir_name = os.path.dirname(WG_CONFIG_PATH)
                    base_name = os.path.basename(WG_CONFIG_PATH)
                    baks = sorted([
                        os.path.join(dir_name, f) for f in os.listdir(dir_name)
                        if f.startswith(f"{base_name}.bak.")
                    ])
                    for old_bak in baks[:-20]:
                        try: os.remove(old_bak)
                        except Exception: pass
                except Exception:
                    pass

            # SAFEGUARD 2: Extract all existing peers from WG_CONFIG_PATH
            # If allow_peer_removal is False, ANY peer in existing file whose public key is NOT in rendered_config
            # MUST BE PRESERVED! Never drop/wipe out existing peers!
            if existing_file_content and not allow_peer_removal:
                existing_peer_blocks = cls.extract_peer_blocks_with_keys(existing_file_content)
                parsed_rendered = cls.parse_config_text(rendered_config)
                rendered_pubkeys = {
                    p["public_key"].strip() for p in (parsed_rendered.get("peers") or []) if p.get("public_key")
                }

                peers_to_preserve = []
                for pub, block in existing_peer_blocks:
                    if pub and pub not in rendered_pubkeys:
                        peers_to_preserve.append(block)

                if peers_to_preserve:
                    logger.warning(f"[SAFEGUARD] Preserved {len(peers_to_preserve)} unmanaged peer blocks in {WG_CONFIG_PATH}")
                    rendered_config = rendered_config.rstrip() + "\n\n" + "\n\n".join(peers_to_preserve) + "\n"

            with open(temp_conf, "w", encoding="utf-8") as f:
                f.write(rendered_config)

            # Strip interface directives if wg-quick available, otherwise parse
            wg_quick_bin = shutil.which("wg-quick")
            if wg_quick_bin:
                try:
                    subprocess.run(
                        [wg_quick_bin, "strip", temp_conf],
                        stdout=open(stripped_conf, "w"),
                        check=True,
                        stderr=subprocess.PIPE
                    )
                except Exception:
                    cls._manual_strip(temp_conf, stripped_conf)
            else:
                cls._manual_strip(temp_conf, stripped_conf)

            # Save full config to permanent path if writable and enforce permissions 0600
            conf_saved = False
            if os.path.exists(os.path.dirname(WG_CONFIG_PATH)) and os.access(os.path.dirname(WG_CONFIG_PATH), os.W_OK):
                with open(WG_CONFIG_PATH, "w", encoding="utf-8") as f:
                    f.write(rendered_config)
                try: os.chmod(WG_CONFIG_PATH, 0o600)
                except Exception: pass
                conf_saved = True


            # Ensure WireGuard link exists
            if ip_bin:
                dev_check = subprocess.run([ip_bin, "link", "show", interface], capture_output=True)
                if dev_check.returncode != 0:
                    add_link = subprocess.run([ip_bin, "link", "add", "dev", interface, "type", "wireguard"], capture_output=True, text=True)
                    if add_link.returncode == 0:
                        subprocess.run([ip_bin, "link", "set", "mtu", "1420", "up", "dev", interface], capture_output=True)
                        # Assign interface IP if configured
                        try:
                            # Extract address from config
                            for line in rendered_config.splitlines():
                                if line.strip().startswith("Address"):
                                    addr = line.split("=")[1].strip()
                                    subprocess.run([ip_bin, "addr", "add", addr, "dev", interface], capture_output=True)
                                    break
                        except Exception:
                            pass

            # Step 3: Production Reload Flow (wgreload or bash wg syncconf <(wg-quick strip))
            reloaded = False
            wgreload_path = "/usr/local/bin/wgreload"
            if os.path.isfile(wgreload_path) and os.access(wgreload_path, os.X_OK):
                proc = subprocess.run([wgreload_path], capture_output=True, text=True)
                if proc.returncode == 0:
                    reloaded = True
                else:
                    return False, f"wgreload error: {proc.stderr.strip()}"

            if not reloaded:
                # Run exact production reload command: bash -c 'wg syncconf wg0 <(wg-quick strip wg0)'
                reload_cmd = f"wg syncconf {interface} <(wg-quick strip {interface})"
                proc = subprocess.run(["bash", "-c", reload_cmd], capture_output=True, text=True)
                if proc.returncode == 0:
                    reloaded = True
                else:
                    # Fallback to direct file strip if interface name lookup failed
                    strip_target = WG_CONFIG_PATH if os.path.exists(WG_CONFIG_PATH) else temp_conf
                    fallback_cmd = f"wg syncconf {interface} <(wg-quick strip {strip_target})"
                    proc2 = subprocess.run(["bash", "-c", fallback_cmd], capture_output=True, text=True)
                    if proc2.returncode == 0:
                        reloaded = True

            if not reloaded:
                # Direct syncconf using generated stripped file
                proc = subprocess.run(
                    [wg_bin, "syncconf", interface, stripped_conf],
                    capture_output=True,
                    text=True
                )
                if proc.returncode != 0:
                    set_proc = subprocess.run(
                        [wg_bin, "setconf", interface, stripped_conf],
                        capture_output=True,
                        text=True
                    )
                    if set_proc.returncode != 0:
                        return False, f"wg syncconf error: {proc.stderr.strip() or set_proc.stderr.strip()}"

            return True, f"Synchronized WireGuard {interface} dynamically with zero downtime."
        except Exception as e:
            return False, f"Failed to apply configuration directly: {str(e)}"
        finally:
            for p in [temp_conf, stripped_conf]:
                if os.path.exists(p):
                    try: os.remove(p)
                    except Exception: pass

    @staticmethod
    def _manual_strip(src_file: str, dst_file: str):
        """Extract only [Peer] directives for syncconf."""
        with open(src_file, "r") as src, open(dst_file, "w") as dst:
            in_peer = False
            for line in src:
                if line.startswith("[Peer]"):
                    in_peer = True
                elif line.startswith("[Interface]"):
                    in_peer = False
                if in_peer:
                    dst.write(line)

    @classmethod
    def _apply_via_agent(cls, rendered_config: str) -> Tuple[bool, str]:
        """Applies configuration through authenticated host agent."""
        if not WG_AGENT_TOKEN:
            return False, "Host agent token (WG_AGENT_TOKEN) is not configured."

        payload = json.dumps({"config": rendered_config}).encode("utf-8")
        timestamp = str(int(time.time()))
        message = f"{timestamp}:{payload.decode('utf-8')}".encode("utf-8")
        sig = hmac.new(WG_AGENT_TOKEN.encode("utf-8"), message, hashlib.sha256).hexdigest()

        req = urllib.request.Request(
            f"{WG_AGENT_URL.rstrip('/')}/apply",
            data=payload,
            headers={
                "Content-Type": "application/json",
                "X-Timestamp": timestamp,
                "X-Signature": sig
            },
            method="POST"
        )
        try:
            with urllib.request.urlopen(req, timeout=10) as resp:
                data = json.loads(resp.read().decode("utf-8"))
                return True, data.get("message", "Success from agent.")
        except Exception as e:
            return False, f"Host agent communication failed: {str(e)}"

    @classmethod
    def get_live_peer_stats(cls, interface: str = WG_INTERFACE) -> Dict[str, dict]:
        """
        Parses `wg show <interface> dump` to retrieve live metrics:
        handshake time, bytes received (rx), and bytes sent (tx).
        """
        stats: Dict[str, dict] = {}
        wg_bin = shutil.which("wg")

        if not wg_bin:
            return stats

        try:
            proc = subprocess.run(
                [wg_bin, "show", interface, "dump"],
                capture_output=True,
                text=True,
                timeout=3
            )
            if proc.returncode != 0:
                return stats

            lines = proc.stdout.strip().splitlines()
            if len(lines) <= 1:
                return stats

            now = int(time.time())
            # Skip first line which is interface information
            for line in lines[1:]:
                parts = line.split("\t")
                if len(parts) >= 8:
                    pub_key = parts[0].strip()
                    endpoint = parts[2].strip() if parts[2] != "(none)" else None
                    allowed_ips = parts[3].strip()
                    handshake_ts = int(parts[4]) if parts[4].isdigit() else 0
                    transfer_rx = int(parts[5]) if parts[5].isdigit() else 0
                    transfer_tx = int(parts[6]) if parts[6].isdigit() else 0

                    is_active = (handshake_ts > 0) and ((now - handshake_ts) < 180) # active within 3 minutes

                    stats[pub_key] = {
                        "endpoint": endpoint,
                        "allowed_ips": allowed_ips,
                        "latest_handshake": handshake_ts,
                        "transfer_rx": transfer_rx,
                        "transfer_tx": transfer_tx,
                        "is_active": is_active,
                        "handshake_readable": cls.format_time_ago(handshake_ts, now),
                        "transfer_rx_readable": cls.format_bytes(transfer_rx),
                        "transfer_tx_readable": cls.format_bytes(transfer_tx)
                    }
        except Exception:
            pass

        return stats

    @staticmethod
    def format_bytes(size: int) -> str:
        """Convert bytes to human-readable string (KB, MB, GB)."""
        if size <= 0:
            return "0 B"
        suffixes = ['B', 'KB', 'MB', 'GB', 'TB']
        idx = 0
        s = float(size)
        while s >= 1024.0 and idx < len(suffixes) - 1:
            s /= 1024.0
            idx += 1
        return f"{s:.2f} {suffixes[idx]}"

    @staticmethod
    def format_time_ago(timestamp: int, current_time: int) -> str:
        """Returns human-friendly relative time string."""
        if not timestamp:
            return "Never"
        diff = max(0, current_time - timestamp)
        if diff < 60:
            return f"{diff}s ago"
        elif diff < 3600:
            return f"{diff // 60}m ago"
        elif diff < 86400:
            return f"{diff // 3600}h ago"
        else:
            return f"{diff // 86400}d ago"
